// MCP server (stdio, newline-delimited JSON-RPC 2.0).
//
// Exposes the worker as MCP tools: shunt_read, shunt_write, shunt_stats.
// Progress messages go to stderr; stdout carries protocol only.

import (
	"bufio"
	"bytes"
	"encoding/json"
	"fmt"
	"io"
	"os"
	"sort"
	"strconv"
	"strings"
)

const latestProtocol = "2025-06-18"

func jsonUnmarshalNumber(data []byte, v any) error {
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.UseNumber()
	if err := dec.Decode(v); err != nil {
		return err
	}
	if dec.More() {
		return fmt.Errorf("unexpected data after JSON value")
	}
	return nil
}

type toolProperty struct {
	Type        string   `json:"type"`
	Items       any      `json:"items,omitempty"`
	Enum        []string `json:"enum,omitempty"`
	Minimum     *int     `json:"minimum,omitempty"`
	Description string   `json:"description"`
	Default     any      `json:"default,omitempty"`
}

type toolSchema struct {
	Type                 string   `json:"type"`
	Properties           record   `json:"properties"`
	Required             []string `json:"required,omitempty"`
	AdditionalProperties bool     `json:"additionalProperties"`
	props                map[string]toolProperty
}

type tool struct {
	Name        string         `json:"name"`
	Description string         `json:"description"`
	InputSchema toolSchema     `json:"inputSchema"`
	Meta        map[string]any `json:"_meta,omitempty"`
}

func schema(required []string, props ...field) toolSchema {
	s := toolSchema{Type: "object", Required: required, Properties: record(props), props: map[string]toolProperty{}}
	for _, p := range props {
		s.props[p.Key] = p.Value.(toolProperty)
	}
	return s
}

